export const plazaVariants = (kind) => ROLES[kind].flatMap((r, variant) => r.role === 'plaza' ? [variant] : []);
export const workersOf = (kind, shopId) => ROLES[kind].map((r, variant) => ({ ...r, variant }))
  .filter(r => r.role === 'worker' && r.shop === shopId).sort((a, b) => a.seat - b.seat).map(r => r.variant);
export const firstVariant = (kind, createdAt) => {
  const plaza = plazaVariants(kind);
  return plaza[hash(`first:${createdAt}`) % plaza.length];
};
